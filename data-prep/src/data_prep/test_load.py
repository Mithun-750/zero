"""Test loader script for quick outbox trigger testing.

Generates a batch of test orders (default: 100), saves to a temporary test file,
inserts them into PostgreSQL, and displays the newly created outbox events.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

from data_prep.generate_orders import generate_orders, save_orders_to_file
from data_prep.load_orders import get_db_connection, insert_order

DEFAULT_COUNT: int = 100


def run_test_load(
    count: int = DEFAULT_COUNT,
    temp_file: str = "data/temp_test_orders.json",
) -> None:
    """Generate test orders, load them, and verify outbox output."""
    print("=" * 70)
    print(f"Running Outbox Test Load ({count} orders)")
    print("=" * 70)

    conn = get_db_connection()

    try:
        # 1. Snapshot initial counts
        with conn.cursor() as cur:
            cur.execute("SELECT count(*) as count FROM orders")
            initial_orders = cur.fetchone()["count"]
            cur.execute("SELECT count(*) as count FROM outbox WHERE status = 'PENDING'")
            initial_outbox = cur.fetchone()["count"]

        print(f"Initial DB State: {initial_orders} orders | {initial_outbox} pending outbox events\n")

        # 2. Generate test orders
        print(f"Generating {count} test orders...")
        test_orders = generate_orders(count)
        saved_path = save_orders_to_file(test_orders, temp_file)
        print(f"Saved test payload to: {saved_path}\n")

        # 3. Insert each order into database
        print("Inserting test orders into PostgreSQL (trigger will populate outbox)...")
        successful_ids: list[str] = []
        is_large_batch = len(test_orders) > 10

        for idx, order in enumerate(test_orders, start=1):
            order_id = str(order.get("id"))
            order_num = order.get("order_number", "UNKNOWN")

            try:
                insert_order(conn, order)
                successful_ids.append(order_id)
                if not is_large_batch:
                    print(f"  [SUCCESS] Order {order_num} | Amount: {order['total_amount']:.2f} {order.get('currency', 'INR')} -> Trigger wrote outbox")
                elif idx % 20 == 0 or idx == len(test_orders):
                    print(f"  Processed {idx}/{len(test_orders)} orders...")
            except Exception as exc:
                print(f"  [ERROR] Failed to insert order {order_num}: {exc}")

        # 4. Query sample newly created outbox records specifically
        if successful_ids:
            sample_ids = successful_ids[:3]
            print(f"\nQuerying sample auto-generated Outbox records ({len(sample_ids)} of {len(successful_ids)}):")
            with conn.cursor() as cur:
                cur.execute(
                    """
                    SELECT id, aggregate_id, event_type, topic, status, created_at, payload
                    FROM outbox
                    WHERE aggregate_id = ANY(%s)
                    ORDER BY created_at ASC
                    """,
                    (sample_ids,),
                )
                rows = cur.fetchall()

            for idx, row in enumerate(rows, start=1):
                payload = row["payload"]
                payment = payload.get("payment_trigger", {})

                print(f"\n--- [Sample Outbox Event #{idx}] ---")
                print(f"  Event ID       : {row['id']}")
                print(f"  Aggregate ID   : {row['aggregate_id']}")
                print(f"  Event Type     : {row['event_type']}")
                print(f"  Kafka Topic    : {row['topic']}")
                print(f"  Status         : {row['status']}")
                print(f"  Customer       : {payload.get('customer_name')} ({payload.get('customer_id')})")
                print(f"  Payment Action : {payment.get('action')}")
                print(f"  Payment Amount : {payment.get('amount')} {payment.get('currency')}")

            if len(successful_ids) > len(sample_ids):
                print(f"\n  ... and {len(successful_ids) - len(sample_ids)} more outbox events registered in database.")

        # 5. Final summary
        with conn.cursor() as cur:
            cur.execute("SELECT count(*) as count FROM orders")
            final_orders = cur.fetchone()["count"]
            cur.execute("SELECT count(*) as count FROM outbox WHERE status = 'PENDING'")
            final_outbox = cur.fetchone()["count"]

        orders_delta = final_orders - initial_orders
        outbox_delta = final_outbox - initial_outbox

        print("\n" + "=" * 70)
        print("Test Execution Summary")
        print("=" * 70)
        print(f"Orders attempted    : {count} (Succeeded: {len(successful_ids)})")
        print(f"Orders in DB        : {initial_orders} -> {final_orders} (+{orders_delta})")
        print(f"Outbox Events in DB : {initial_outbox} -> {final_outbox} (+{outbox_delta} auto-generated by trigger)")
        print("=" * 70)

    finally:
        conn.close()


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Quick test script to generate and load test orders to verify the Outbox trigger."
    )
    parser.add_argument(
        "-c",
        "--count",
        type=int,
        default=DEFAULT_COUNT,
        help=f"Number of test orders to generate and load (default: {DEFAULT_COUNT})",
    )
    parser.add_argument(
        "-t",
        "--temp-file",
        type=str,
        default="data/temp_test_orders.json",
        help="Path for temporary test JSON file (default: data/temp_test_orders.json)",
    )
    args = parser.parse_args()
    run_test_load(
        count=args.count,
        temp_file=args.temp_file,
    )


if __name__ == "__main__":
    main()
